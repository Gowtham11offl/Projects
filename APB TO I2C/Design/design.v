
`timescale 1ns/1ps  // Defines simulation time unit as 1ns and precision as 1ps.

// Include the required sub-module Verilog files.
`include "i2c_clk_gen.v"      // I2C clock generation module.
`include "i2c_byte_cntrl.v"   // I2C byte-level controller.
`include "i2c_bit_cntrl.v"    // I2C bit-level controller.
`include "i2c_slave.v"        // I2C slave module.

// Top-level module connecting APB interface and I2C controller.
module apb_i2c_core (

    // ---------------- APB Bus Interface Ports ----------------

    input  wire        PCLK,       // APB system clock.
    input  wire        PRESETn,    // Active-low asynchronous reset.
    input  wire [31:0] PADDR,      // APB address bus used to select registers.
    input  wire        PSEL,       // Select signal indicates peripheral selection.
    input  wire        PENABLE,    // Indicates APB access phase.
    input  wire        PWRITE,     // 1 = Write operation, 0 = Read operation.
    input  wire [31:0] PWDATA,     // Data sent from APB master to I2C registers.
    output reg  [31:0] PRDATA,     // Data returned from I2C registers to APB master.
    output wire        PREADY,     // Indicates that APB transfer is complete.

    // ---------------- Physical Bidirectional I2C Pins ----------------

    inout  wire        scl,        // Bidirectional I2C serial clock line.
    inout  wire        sda         // Bidirectional I2C serial data line.

);

// ========================================================================
// 1. REGISTER DECLARATIONS
// These registers are accessed by the APB master.
// ========================================================================

reg [7:0] prer_lo;  // Lower 8 bits of the I2C clock prescaler.
reg [7:0] prer_hi;  // Upper 8 bits of the I2C clock prescaler.
reg [7:0] ctr;      // Control register: enables the I2C core.

reg [7:0] txr;      // Transmit register: stores the data to be transmitted.
wire [7:0] rxr;     // Receive register: holds the received I2C data.

reg [7:0] cr;       // Command register: stores START, STOP, READ and WRITE commands.
wire [7:0] sr;      // Status register: indicates the current I2C controller status.

// ========================================================================
// 2. INTERNAL WIRES CONNECTING THE SUB-MODULES
// These wires transfer signals between clock, bit and byte controllers.
// ========================================================================

wire        clk_en;        // Enable pulse generated by the clock generator.
wire        bit_din;       // Serial input data sent to the bit controller.
wire        bit_dout;      // Serial data received from the bit controller.
wire        bit_ack;       // Indicates completion of a bit-level operation.

wire        scl_oen;       // Controls whether the I2C SCL line is pulled LOW or released.
wire        sda_oen;       // Controls whether the I2C SDA line is pulled LOW or released.
wire        scl_in;        // Reads the actual logic level present on the SCL bus.
wire        sda_in;        // Reads the actual logic level present on the SDA bus.

wire [7:0]  byte_dout;     // 8-bit data received from the byte controller.
wire        byte_ack;      // Indicates completion of a byte-level operation.
wire        byte_ack_out;  // Acknowledgement information from the byte controller.
wire        i2c_busy;      // Indicates whether the I2C bus is busy.

// ========================================================================
// 3. APB READ/WRITE DECODE LOGIC
// Determines whether the APB master is performing a read or write.
// ========================================================================

assign PREADY = 1'b1;  
// Always HIGH, indicating that the peripheral does not insert wait states.

wire apb_write = PSEL & PENABLE & PWRITE & PREADY;
// Write occurs when the peripheral is selected, access phase is active,
// PWRITE is HIGH and the peripheral is ready.

wire apb_read = PSEL & PENABLE & ~PWRITE & PREADY;
// Read occurs when the peripheral is selected, access phase is active,
// PWRITE is LOW and the peripheral is ready.

// ========================================================================
// 4. APB REGISTER WRITE LOGIC
// Transfers data from the APB master into the internal registers.
// ========================================================================

always @(posedge PCLK or negedge PRESETn) begin
// Executes on the rising edge of PCLK or falling edge of reset.

    if (!PRESETn) begin
    // When reset is LOW, initialize all writable registers.

        prer_lo <= 8'hFF;  // Reset lower prescaler register to FF.
        prer_hi <= 8'hFF;  // Reset upper prescaler register to FF.
        ctr     <= 8'h00;  // Disable the I2C core after reset.
        txr     <= 8'h00;  // Clear the transmit register.
        cr      <= 8'h00;  // Clear all command register bits.

    end else begin
    // Normal operation when reset is HIGH.

        if (apb_write) begin
        // Execute register write when an APB write transaction occurs.

            case (PADDR[2:0])
            // Select the register using the three least significant address bits.

                3'h0: prer_lo <= PWDATA[7:0];
                // Address 0: Write the lower prescaler byte.

                3'h1: prer_hi <= PWDATA[7:0];
                // Address 1: Write the upper prescaler byte.

                3'h2: ctr <= PWDATA[7:0];
                // Address 2: Write the control register.

                3'h3: txr <= PWDATA[7:0];
                // Address 3: Write the transmit register.

                3'h4: cr <= PWDATA[7:0];
                // Address 4: Write the command register.

                default: ;
                // No operation for unsupported addresses.

            endcase

        end else begin
        // Execute this section when there is no APB write.

            if (byte_ack) begin
            // When byte-level operation completes, clear command bits.

                cr[7:4] <= 4'b0000;
                // Clear START, STOP, READ and WRITE command bits.

            end
        end
    end
end

// ========================================================================
// 5. APB REGISTER READ LOGIC
// Transfers internal register values to the APB master.
// ========================================================================

always @(*) begin
// Combinational logic: continuously evaluates whenever an input changes.

    PRDATA = 32'h0000_0000;
    // Default read data is zero to avoid unintended values.

    if (apb_read) begin
    // Perform register selection only during an APB read transaction.

        case (PADDR[2:0])
        // Decode the address to select the required register.

            3'h0: PRDATA[7:0] = prer_lo;
            // Address 0: Return lower prescaler value.

            3'h1: PRDATA[7:0] = prer_hi;
            // Address 1: Return upper prescaler value.

            3'h2: PRDATA[7:0] = ctr;
            // Address 2: Return control register value.

            3'h3: PRDATA[7:0] = rxr;
            // Address 3: Return received I2C data.

            3'h4: PRDATA[7:0] = sr;
            // Address 4: Return I2C status information.

            default: PRDATA[7:0] = 8'h00;
            // Return zero for unsupported addresses.

        endcase
    end
end

// ========================================================================
// 6. STATUS REGISTER AND RECEIVE REGISTER CONNECTIONS
// Connects byte controller outputs to the APB-visible registers.
// ========================================================================

assign rxr = byte_dout;
// The received 8-bit data from the byte controller is available through RXR.

assign sr[7] = byte_ack_out;
// Status bit 7 represents the byte controller acknowledgement output.

assign sr[6] = i2c_busy;
// Status bit 6 indicates whether the I2C bus is busy.

assign sr[5:2] = 4'b0000;
// Status bits 5, 4, 3 and 2 are unused and tied to zero.

assign sr[1] = i2c_busy;
// Status bit 1 is also connected to the I2C busy signal in this implementation.

assign sr[0] = byte_ack;
// Status bit 0 indicates completion of a byte-level operation.

// ========================================================================
// 7. PHYSICAL BIDIRECTIONAL I2C BUFFERS
// Implements open-drain behaviour for SCL and SDA.
// I2C devices can pull the bus LOW or release it to HIGH.
// External pull-up resistors produce the HIGH level.
// ========================================================================

assign scl = (scl_oen == 1'b0) ? 1'b0 : 1'bz;
// If scl_oen is 0, drive SCL LOW.
// If scl_oen is 1, release SCL by driving high impedance (Z).

assign sda = (sda_oen == 1'b0) ? 1'b0 : 1'bz;
// If sda_oen is 0, drive SDA LOW.
// If sda_oen is 1, release SDA by driving high impedance (Z).

assign scl_in = scl;
// Read the actual SCL bus voltage/logic level into the internal signal.

assign sda_in = sda;
// Read the actual SDA bus voltage/logic level into the internal signal.

// ========================================================================
// 8. MODULE INSTANTIATIONS
// Connects the clock generator, bit controller and byte controller.
// ========================================================================

// ---------------- I2C CLOCK GENERATOR ----------------

i2c_clk_gen u_clock_gen (
// Creates the clock enable signal required for I2C timing.

    .clk(PCLK),
    // System clock is connected to the clock generator.

    .rst_n(PRESETn),
    // Active-low reset is connected to the clock generator.

    .prescale({prer_hi, prer_lo}),
    // Combines upper and lower prescaler registers into a 16-bit value.

    .scl_out(scl_oen),
    // Receives the SCL output-enable control from the clock generator.

    .scl_in(scl_in),
    // Feeds the actual SCL bus level back to the clock generator.

    .clk_en(clk_en)
    // Provides the timing enable pulse to the bit controller.

);

// ---------------- I2C BIT CONTROLLER ----------------

i2c_bit_cntrl u_bit_ctrl (
// Performs individual I2C bit operations such as START, STOP, READ and WRITE.

    .clk(PCLK),
    // System clock input.

    .rst_n(PRESETn),
    // Active-low reset input.

    .clk_en(clk_en),
    // Enables the bit controller at the required I2C timing intervals.

    .cmd(bit_cmd),
    // Receives the bit-level command from the byte controller.

    .din(bit_din),
    // Receives the serial data bit to be transmitted.

    .dout(bit_dout),
    // Sends the received serial data bit back to the byte controller.

    .cmd_ack(bit_ack),
    // Indicates that the requested bit operation has completed.

    .scl_oen(scl_oen),
    // Controls whether the physical SCL line is driven LOW or released.

    .sda_oen(sda_oen),
    // Controls whether the physical SDA line is driven LOW or released.

    .scl_in(scl_in),
    // Reads the actual SCL bus level.

    .sda_in(sda_in)
    // Reads the actual SDA bus level.

);

// ---------------- I2C BYTE CONTROLLER ----------------

i2c_byte_cntrl u_byte_ctrl (
// Handles complete 8-bit I2C data transfers and coordinates bit operations.

    .clk(PCLK),
    // System clock input.

    .rst_n(PRESETn),
    // Active-low reset input.

    .start(cr[7] & ctr[7]),
    // START command is enabled when CR[7] and CTR[7] are both HIGH.

    .stop(cr[6] & ctr[7]),
    // STOP command is enabled when CR[6] and CTR[7] are both HIGH.

    .read(cr[5] & ctr[7]),
    // READ command is enabled when CR[5] and CTR[7] are both HIGH.

    .write(cr[4] & ctr[7]),
    // WRITE command is enabled when CR[4] and CTR[7] are both HIGH.

    .ack_in(cr[3]),
    // Supplies the acknowledgement control bit from the command register.

    .din(txr),
    // Supplies the 8-bit data stored in the transmit register.

    .dout(byte_dout),
    // Returns the received 8-bit data from the byte controller.

    .cmd_ack(byte_ack),
    // Indicates completion of a byte-level operation.

    .ack_out(byte_ack_out),
    // Returns acknowledgement information from the byte controller.

    .i2c_busy(i2c_busy),
    // Indicates whether an I2C transaction is currently active.

    .bit_cmd(bit_cmd),
    // Sends bit-level commands to the bit controller.

    .bit_din(bit_din),
    // Sends individual data bits to the bit controller.

    .bit_dout(bit_dout),
    // Receives individual data bits from the bit controller.

    .bit_ack(bit_ack)
    // Receives completion acknowledgement from the bit controller.

);

endmodule
// End of the top-level APB-I2C core module.
